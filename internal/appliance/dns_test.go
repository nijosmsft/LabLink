func TestParseResolvectlObservationUsesExactMainLink(t *testing.T) {
	dnsOutput := `Global: 9.9.9.9
Link 2 (eth0): 10.0.0.2 127.0.0.53 10.0.0.2 192.168.240.1 0.0.0.0 224.0.0.1 10.0.0.3 10.0.0.4 10.0.0.5
Link 3 (eth1): 192.168.240.1`
	domainOutput := `Link 2 (eth0): corp.example ~internal.example dev.example lab.example extra.example fifth.example sixth.example seventh.example
Link 3 (eth1): private.example`
	observation := ParseResolvectlObservation(
		dnsOutput,
		domainOutput,
		"eth0",
		[]netip.Addr{netip.MustParseAddr("192.168.240.1")},
	)
	wantServers := []netip.Addr{
		netip.MustParseAddr("10.0.0.2"),
		netip.MustParseAddr("10.0.0.3"),
		netip.MustParseAddr("10.0.0.4"),
	}
	if len(observation.Servers) != len(wantServers) {
		t.Fatalf("servers = %v, want %v", observation.Servers, wantServers)
	}
	for index := range wantServers {
		if observation.Servers[index] != wantServers[index] {
			t.Fatalf("servers = %v, want %v", observation.Servers, wantServers)
		}
	}
	if observation.State != DNSStateReady || !observation.Truncated {
		t.Fatalf("unexpected state/truncation: %+v", observation)
	}
	if len(observation.SplitDomains) != 1 || observation.SplitDomains[0] != "~internal.example" {
		t.Fatalf("split domains = %v", observation.SplitDomains)
	}
	if len(observation.SearchDomains) != 6 {
		t.Fatalf("search domains = %v, want six", observation.SearchDomains)
	}
	for _, rejected := range observation.Rejected {
		if rejected.Value == "9.9.9.9" || rejected.Value == "192.168.240.1" && rejected.Reason == "" {
			t.Fatalf("unexpected resolver filtering result: %+v", observation.Rejected)
		}
	}
	if len(observation.Rejected) != 4 {
		t.Fatalf("rejected = %+v, want loopback/private gateway/unspecified/multicast", observation.Rejected)
	}
}

func TestNoUsableDNSReturnsTypedErrorWithSplitDNSLimit(t *testing.T) {
	observation := ParseResolvectlObservation(
		"Link 2 (eth0): 127.0.0.53 169.254.1.1",
		"Link 2 (eth0): ~corp.example",
		"eth0",
		nil,
	)
	if observation.State != DNSStateNoUpstreamResolver {
		t.Fatalf("state = %q", observation.State)
	}
	err := RequireUpstreamDNS(observation)
	var unavailable *DNSUnavailableError
	if !errors.As(err, &unavailable) {
		t.Fatalf("error = %T %v, want DNSUnavailableError", err, err)
	}
	for _, want := range []string{"no usable upstream IPv4 resolver", "split-DNS routing domains cannot be represented"} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("error %q missing %q", err, want)
		}
	}
}

func TestParseResolvedResolvConfRejectsStub(t *testing.T) {
	observation := ParseResolvedResolvConf(`# generated by systemd-resolved
nameserver 127.0.0.53
nameserver 10.30.0.2
search corp.example
`, "eth0", nil)
	if len(observation.Servers) != 1 || observation.Servers[0] != netip.MustParseAddr("10.30.0.2") {
		t.Fatalf("servers = %v", observation.Servers)
	}
	if len(observation.SearchDomains) != 1 || observation.SearchDomains[0] != "corp.example" {
		t.Fatalf("search domains = %v", observation.SearchDomains)
	}
	if len(observation.Rejected) != 1 || !strings.Contains(observation.Rejected[0].Reason, "stub") {
		t.Fatalf("rejected = %+v", observation.Rejected)
	}
}
